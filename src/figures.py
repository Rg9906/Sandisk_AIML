"""
All plots. Deliverable 4 lives here.

Every figure is auto-generated by `run_pipeline.py` -- nothing is hand-made in a
notebook, so a judge asking "can you regenerate that?" gets a yes.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")                      # headless: no display on the demo machine
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

FIG_DIR = Path("figures")
DPI = 130

# Consistent semantics across every wafer plot in the deck.
CMAP_RISK = "inferno"
COL_PASS, COL_OLD_FAIL, COL_NEW_FAIL, COL_EMPTY = "#2e7d32", "#c62828", "#ef6c00", "#f0f0f0"


def _ensure() -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)


def _grid_from(preds_df: pd.DataFrame, value: str, shape: tuple[int, int]) -> np.ndarray:
    g = np.full(shape, np.nan)
    g[preds_df["die_y"].to_numpy(), preds_df["die_x"].to_numpy()] = preds_df[value].to_numpy()
    return g


def wafer_heatmap(preds: list, dies: pd.DataFrame, wafer_id: str,
                  out: str = "wafer_heatmap.png") -> Path:
    """
    Three panels: pre-test state, predicted risk, ground truth.

    This is the figure the demo opens on -- it shows at a glance that the model is
    finding structure, not sprinkling probability uniformly.
    """
    _ensure()
    w = dies[dies["wafer_id"] == wafer_id]
    shape = (int(w["die_row"].max()) + 1, int(w["die_col"].max()) + 1)

    pdf = pd.DataFrame([{
        "die_x": p.die_x, "die_y": p.die_y, "p_fail": p.p_fail,
        "y_true": p.y_true, "y_pred": p.y_pred,
    } for p in preds if p.wafer_id == wafer_id])

    fig, axes = plt.subplots(1, 3, figsize=(15, 5.2))

    # Panel 1 -- what the fab sees before this test round.
    pre = np.full(shape, 0.0)
    pre[w["die_row"].to_numpy(), w["die_col"].to_numpy()] = 1.0
    old = w[w["old_label"] == 1]
    pre[old["die_row"].to_numpy(), old["die_col"].to_numpy()] = 2.0
    cmap = matplotlib.colors.ListedColormap([COL_EMPTY, COL_PASS, COL_OLD_FAIL])
    axes[0].imshow(pre, cmap=cmap, vmin=0, vmax=2, interpolation="nearest")
    axes[0].set_title(f"Pre-test  ({wafer_id})\ngreen = pass, red = known fail")

    if len(pdf):
        risk = _grid_from(pdf, "p_fail", shape)
        im = axes[1].imshow(risk, cmap=CMAP_RISK, vmin=0, vmax=max(0.2, np.nanmax(risk)),
                            interpolation="nearest")
        fig.colorbar(im, ax=axes[1], fraction=0.046)
        axes[1].set_title("Predicted risk\n(eligible dies only)")

        # Panel 3 -- truth, with the same colour semantics as panel 1 plus new fails.
        post = pre.copy()
        newf = pdf[pdf["y_true"] == 1]
        post[newf["die_y"].to_numpy(), newf["die_x"].to_numpy()] = 3.0
        cmap3 = matplotlib.colors.ListedColormap(
            [COL_EMPTY, COL_PASS, COL_OLD_FAIL, COL_NEW_FAIL])
        axes[2].imshow(post, cmap=cmap3, vmin=0, vmax=3, interpolation="nearest")
        axes[2].set_title("Post-test truth\norange = NEW failure (our target)")

    for a in axes:
        a.set_xticks([]); a.set_yticks([])
    fig.tight_layout()
    path = FIG_DIR / out
    fig.savefig(path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    return path


def attribution_bar(pred, out: str = "attribution.png") -> Path:
    """
    THE signature visual: how much of this die's risk came from each resolution.

    Not "which features" -- "which *level of the hierarchy*". That is the question
    deliverable 4 asks and the one a process engineer actually acts on.
    """
    _ensure()
    fams = ["die", "spatial", "block"]
    vals = [pred.attribution.get(f, 0.0) for f in fams]
    colors = ["#1565c0", "#6a1b9a", "#00838f"]

    fig, ax = plt.subplots(figsize=(7.5, 2.9))
    bars = ax.barh(fams, vals, color=colors, height=0.62)
    for b, v in zip(bars, vals):
        ax.text(v + 0.012, b.get_y() + b.get_height() / 2, f"{v:.2f}",
                va="center", fontsize=11, fontweight="bold")

    ax.set_xlim(0, max(0.6, max(vals) * 1.25))
    ax.set_xlabel("share of prediction")
    title = f"Die ({pred.die_y}, {pred.die_x}) - risk {pred.p_fail:.2f}"
    if pred.root_cause:
        title += f"\n{pred.root_cause}"
    ax.set_title(title, fontsize=10, loc="left")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    path = FIG_DIR / out
    fig.savefig(path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    return path


def shap_waterfall(explainer, X: pd.DataFrame, row: int,
                   out: str = "shap_waterfall.png") -> Path | None:
    """Per-die SHAP waterfall -- the standard local explanation, for one predicted fail."""
    _ensure()
    try:
        import shap
        ex = explainer(X.iloc[[row]])
        if ex.values.ndim == 3:
            ex = ex[:, :, 1]
        fig = plt.figure(figsize=(9, 5.5))
        shap.plots.waterfall(ex[0], max_display=12, show=False)
        path = FIG_DIR / out
        fig.savefig(path, dpi=DPI, bbox_inches="tight")
        plt.close(fig)
        return path
    except Exception as exc:
        print(f"  !! waterfall skipped ({exc})")
        plt.close("all")
        return None


def pr_curves(curves: dict, out: str = "pr_curves.png") -> Path:
    """Precision-recall curves for every model and baseline on one axis."""
    _ensure()
    from sklearn.metrics import average_precision_score, precision_recall_curve

    fig, ax = plt.subplots(figsize=(7, 5.5))
    for name, (y, p) in curves.items():
        if len(np.unique(y)) < 2:
            continue
        pr, rc, _ = precision_recall_curve(y, p)
        ap = average_precision_score(y, p)
        ax.plot(rc, pr, label=f"{name}  (AUC-PR {ap:.3f})", linewidth=2)

    base = float(np.mean(list(curves.values())[0][0]))
    ax.axhline(base, ls="--", c="grey", lw=1,
               label=f"random / all-pass ({base:.3f})")
    ax.set_xlabel("recall (fail class)")
    ax.set_ylabel("precision (fail class)")
    ax.set_title("Precision-Recall on the minority class")
    ax.legend(fontsize=9)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    path = FIG_DIR / out
    fig.savefig(path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    return path
